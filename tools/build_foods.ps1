  $display = $it[0]; $match = $it[1]; $cat = $it[2]; $liquid = $it[3]; $units = $it[4]
  $rec = $byName[$match]
  if (-not $rec) {
    # 模糊匹配：去掉括号内容后比对，或包含匹配
    $base = ($match -replace '（.*$','')
    $rec = $records | Where-Object { $_.name -eq $match -or ($_.name -replace '（.*$','') -eq $base } | Select-Object -First 1
  }
  if (-not $rec) { $miss += $match; continue }
  $id++
  $foods += [ordered]@{
    id = ('f{0:D3}' -f $id)
    name = $display
    category = $cat
    is_liquid = if ($liquid) { 1 } else { 0 }
    per100 = [ordered]@{
      energy = Num $rec.kcal; protein = Num $rec.protein; fat = Num $rec.fat
      carbs = Num $rec.cho; sodium = Num $rec.na; calcium = Num $rec.ca
